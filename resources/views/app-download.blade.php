            // لینکِ متنیِ زیرش همچنان قابل استفاده است؛ صفحه نمی‌شکند.
            var qr = window.MeraatPresenceQr;

            if (!canvas || !qr || typeof qr.qrCells !== 'function' || typeof qr.paint !== 'function') {
                return;
            }

            var cells = qr.qrCells(url);

            if (cells) {
                qr.paint(canvas, cells, 8);
