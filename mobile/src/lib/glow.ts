/**
 * حسابِ جابه‌جایی لکه‌های نوریِ سرصفحه وقتی انگشت روی کادر کشیده می‌شود.
 *
 * چرا جدا و بدون هیچ وابستگی: خودِ حرکت با `Animated` اجرا می‌شود، ولی «کدام
 * لکه و چقدر» فقط یک حساب ساده است — و همین‌جا می‌شود بی گوشی و بی رندر
 * تستش کرد. قاعدهٔ خواسته‌شده هم همین است: هر لکه هر چه به انگشت نزدیک‌تر
 * باشد سهم بیشتری می‌گیرد، و جابه‌جایی **خلافِ** کشیدن انگشت است.
 *
 * مدلِ ساده و آگاهانه: مبنای جابه‌جایی، فاصلهٔ انگشت از *نقطهٔ شروعِ لمس* است،
 * نه سرعتِ لحظه‌ای. چرا: سرعتِ لحظه‌ای به نرخ رویدادهای لمسی وابسته است و روی
 * گوشیِ ۱۲۰ هرتز یک رفتار و روی ۶۰ هرتز رفتار دیگری می‌داد. با مبنا قرار دادن
 * جابه‌جایی، «کشیدنِ ۶۰ پیکسلی» همیشه یک نتیجه می‌دهد و انگشت که برگردد، لکه
 * هم برمی‌گردد.
 */

export type Point = { x: number; y: number };

/** اندازهٔ کادرِ سرصفحه، برای نرمال‌کردن فاصله‌ها. */
export type Box = { width: number; height: number };

/** هر پیکسل کشیدنِ انگشت، چند پیکسل لکه را در جهت مخالف می‌بَرد. */
export const GLOW_PULL = 0.45;

/** سقفِ جابه‌جایی هر لکه؛ بیشتر از این، لکه از کادر بیرون می‌زند. */
export const GLOW_MAX = 28;

/**
 * مقیاسِ «نزدیکی». کوچک باشد، فقط لکهٔ دقیقاً زیر انگشت تکان می‌خورد؛ بزرگ
 * باشد، هر دو لکه یک‌اندازه جابه‌جا می‌شوند. این عدد وسط را می‌گیرد: لکهٔ دور
 * حدود یک‌پنجمِ لکهٔ نزدیک حرکت می‌کند.
 */
const NEAR = 0.35;

function clamp(value: number, max: number): number {
  const bounded = Math.max(-max, Math.min(max, value));

  // صفرِ منفی به همین سادگی جا می‌ماند (حاصل‌ضرب `-0 * n`) و بعد در مقایسه‌های
  // بعدی غافلگیرکننده است؛ پس همه‌جا یک صفرِ ساده برگردانده می‌شود.
  return bounded === 0 ? 0 : bounded;
}

/**
 * سهمِ هر لکه از حرکت انگشت — عددِ ۰ تا ۱، که نزدیک‌ترین لکه همیشه ۱ می‌گیرد.
 *
 * `centers` مرکز هر لکه در دستگاه مختصات نرمالِ کادر (۰ تا ۱) است، پس مستقل از
 * اندازهٔ گوشی است؛ این مراکز عمداً می‌توانند بیرونِ ۰..۱ هم باشند، چون لکه‌ها
 * روی گوشه‌های کادر نشسته‌اند و نیمهٔ بیرونشان بیرونِ کادر است.
 */
export function glowShares(
  finger: Point,
  size: Box,
  centers: readonly Point[],
): number[] {
  if (centers.length === 0) return [];

  // اندازهٔ صفر یعنی هنوز چیدمان نیامده؛ آن‌وقت هر دو لکه سهم برابر می‌گیرند.
  const nx = size.width > 0 ? finger.x / size.width : 0;
  const ny = size.height > 0 ? finger.y / size.height : 0;

  const raw = centers.map((center) => {
    const dx = nx - center.x;
    const dy = ny - center.y;
    return 1 / (NEAR + dx * dx + dy * dy);
  });

  const top = Math.max(...raw);

  return raw.map((value) => value / top);
}

/**
 * جابه‌جایی هر لکه برای یک لحظه از کشیدن.
 *
 * `finger` و `origin` در دستگاه مختصات خودِ کادر و به پیکسل‌اند (نقطهٔ شروع و
 * جای فعلی انگشت)، `size` اندازهٔ همان کادر است و `centers` مرکز لکه‌ها به
 * مختصات نرمال. خروجی برای هر لکه یک جابه‌جاییِ پیکسلی است که باید به ترنسفورم
 * آن اضافه شود.
 */
export function pushGlows(
  finger: Point,
  origin: Point,
  size: Box,
  centers: readonly Point[],
  max = GLOW_MAX,
): Point[] {
  const dx = finger.x - origin.x;
  const dy = finger.y - origin.y;

  return glowShares(finger, size, centers).map((share) => ({
    // علامت منفی عمدی است: لکه در جهت *مخالف* کشیدن انگشت می‌رود.
    x: clamp(-dx * GLOW_PULL * share, max),
    y: clamp(-dy * GLOW_PULL * share, max),
  }));
}
