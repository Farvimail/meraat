/**
 * «اتصال به سرور برقرار نیست» — زبانی مشترک برای هر جایی که درخواست می‌شود.
 *
 * جایی که این حالت واقعاً مهم است صفحهٔ ورود است: اگر گوشی اینترنت نداشته باشد
 * کاربر نباید بی‌خبر بماند و دکمهٔ «ورود» را بی‌فایده بزند. اپ ولی از همان
 * قاعده در هر درخواست استفاده می‌کند تا وضعیت اتصال صفحه‌ها یکی بماند.
 */

export type ConnectionState = 'checking' | 'online' | 'offline';

/** فاصلهٔ تلاشِ خودکار وقتی اتصال قطع است (میلی‌ثانیه). */
export const CONNECTION_RETRY_MS = 5000;

/**
 * خطای یک درخواست → «راه باز بود یا نه».
 *
 * هر پاسخی از سرور یعنی اتصال برقرار است، حتی ۴۰۱ (هنوز توکن نداریم) و ۵۰۰
 * (سرور خراب است): در این حالت‌ها کاربر باید همان پاسخ را ببیند، نه پیامِ
 * «اینترنت وصل نیست». فقط خطای شبکه و تمام‌شدنِ مهلت یعنی هیچ پاسخی نیامده.
 *
 * خطای ناشناخته (باگِ خودِ اپ) هم «قطع» شمرده نمی‌شود؛ چسباندنِ پیامِ
 * «اینترنت نیست» به آن، کاربر را دنبالِ مشکلی می‌فرستد که وجود ندارد.
 */
export function reachableFromError(error: unknown): boolean {
  // کد خطا از روی شکلِ خودِ خطا خوانده می‌شود (همان کاری که `messageForError`
  // در `messages.ts` می‌کند): این‌طور این ماژول به `api.ts` وابسته نمی‌شود و
  // اگر روزی خطاها از لایهٔ دیگری بیایند هم همین قاعده کار می‌کند.
  if (error && typeof error === 'object' && 'code' in error) {
    const code = (error as { code: unknown }).code;

    return code !== 'network' && code !== 'timeout';
  }

  return true;
}

/** جملهٔ وضعیت برای نمایش زیر عنوانِ «اتصال به سرور برقرار نیست». */
export function connectionNote(state: ConnectionState): string {
  if (state === 'checking') return 'در حال بررسی اتصال به سرور…';

  if (state === 'offline') {
    return 'اینترنتِ این گوشی یا شبکهٔ محل کار را بررسی کنید؛ هر چند ثانیه خودمان دوباره تلاش می‌کنیم.';
  }

  return '';
}
