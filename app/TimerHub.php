<?php

namespace App;

use App\Http\Controllers\TimerController;

/*
|--------------------------------------------------------------------------
| خبر کردنِ پنل از یک ثبتِ تازه (Timer hub)
|--------------------------------------------------------------------------
|
| پنل با درخواست‌های دوره‌ای می‌فهمید که ثبتِ تازه‌ای انجام شده؛ حتی با بهترین
| تنظیم، «تا نوبتِ درخواستِ بعدی» تأخیر داشت و در عمل ثبتِ گوشی چند ثانیه بعد
| روی سایت دیده می‌شد. اینجا سرور خودش خبر می‌دهد: به‌محضِ نوشتنِ رکورد، یک
| درخواستِ کوچک به هابِ WebSocket می‌رود و هاب همان لحظه به پنل‌های باز
| می‌گوید «کارمندِ فلان عوض شد». پنل فقط همان کارت را می‌خواند.
|
| سه قرارِ مهم این کلاس:
|
|   ۱) **هیچ‌وقت خطا پرت نمی‌کند.** ثبتِ حضور نباید به‌خاطرِ یک سرویسِ جانبی
|      شکست بخورد. خطاها بلعیده می‌شوند و پنل به همان تازه‌سازیِ دوره‌ای
|      برمی‌گردد — یعنی مسیرِ قدیمی همیشه به‌عنوان پشتیبان سر جایش است.
|   ۲) **کوتاه صبر می‌کند.** مهلت (timeout) چند صد میلی‌ثانیه است تا پاسخِ ثبتِ
|      کاربر پشتِ هابِ خواب‌رفته نماند. اگر هاب جواب ندهد، خبر از دست می‌رود و
|      تازه‌سازیِ دوره‌ای جبرانش می‌کند.
|   ۳) **بدونِ وابستگی.** بیلدِ PHP این پروژه `ext-curl` ندارد، پس با
|      streamِ داخلیِ PHP فرستاده می‌شود.
|
| خاموش‌کردن: اگر `TIMER_HUB_SECRET` خالی باشد (پیش‌فرض)، این کلاس کامل
| بی‌اثر است و سامانه مثل قبل کار می‌کند. پس استقرارِ کد بدون راه‌اندازیِ هاب
| هیچ چیزی را نمی‌شکند.
*/

class TimerHub
{
    /** مهلتِ کلِ درخواست (ثانیه) — عمداً کسری از ثانیه. */
    const TIMEOUT = 0.4;

    /**
     * «کارمندِ فلان عوض شد» را به هاب می‌گوید.
     *
     * @param  int|string  $customerId
     * @param  string|null $dmy        روزِ رکوردِ ثبت‌شده (اگر معلوم است)
     */
    public static function announce($customerId, $dmy = null)
    {
        $url = rtrim((string) config('services.timer_hub.url'), '/');
        $secret = (string) config('services.timer_hub.secret');

        if ($url === '' || $secret === '')
            return;

        $payload = json_encode([
            'dmy' => $dmy ?: TimerController::findToday(),
            'id' => (int) $customerId,
            // «انگشتِ تغییر» فقط برای شناختنِ نسخه در لاگِ هاب است؛ تصمیمِ
            // تازه‌سازی را پنل خودش با خواندنِ رکوردها می‌گیرد.
            'revision' => date('His'),
        ]);

        try {
            $context = stream_context_create([
                'http' => [
                    'method' => 'POST',
                    'header' => "Content-Type: application/json\r\n"
                        . "X-Meraat-Secret: {$secret}\r\n"
                        . 'Content-Length: ' . strlen($payload) . "\r\n",
                    'content' => $payload,
                    'timeout' => self::TIMEOUT,
                    // کدِ ۴xx/۵xx نباید هشدار بدهد: خطا اینجا بی‌اهمیت است.
                    'ignore_errors' => true,
                ],
            ]);

            @file_get_contents($url . '/publish', false, $context);
        } catch (\Throwable $error) {
            // بی‌صدا: پنل مسیرِ دوره‌ای را دارد.
        }
    }
}
